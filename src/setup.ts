/**
 * Builds the one-time setup for the machine that owns the microphone.
 *
 * pi can run on a host with no usable audio input while the microphone is on
 * the machine running the terminal. That machine needs two things: a helper
 * that records on demand, and an SSH entry that starts it and forwards its
 * port. This module writes both into one script that the user runs there, so
 * the client needs no package manager, repository, or manual editing.
 */
import { readFile, writeFile } from "node:fs/promises";

/** Script the user copies from this host and runs on the machine with the mic. */
export const SETUP_SCRIPT = "/tmp/pi-dictation-setup.sh";

/** The helper ships with the package; the client gets a copy of it. */
const HELPER_PATH = new URL("../scripts/pi-mic-stream", import.meta.url);

/**
 * Reads the host name from the command argument. Only host-name characters are
 * accepted because the value is written into an SSH config file.
 */
export function parseHost(args: string): string | undefined {
	const host = args.trim().split(/\s+/)[0] ?? "";
	return /^[A-Za-z0-9._-]+$/.test(host) ? host : undefined;
}

export async function readHelper(): Promise<string> {
	return readFile(HELPER_PATH, "utf8");
}

export function setupScript(host: string, helper: string): string {
	return `#!/bin/sh
# One-time setup for pi-push-to-talk on the machine with the microphone.
# Generated by /dictation-setup; safe to run again.
set -eu

mkdir -p "$HOME/.local/bin" "$HOME/.ssh/config.d"

cat > "$HOME/.local/bin/pi-mic-stream" <<'HELPER_EOF'
${helper.trimEnd()}
HELPER_EOF
chmod +x "$HOME/.local/bin/pi-mic-stream"

# OpenSSH reads only ~/.ssh/config, so drop-ins need one Include line.
if ! grep -q 'config\\.d' "$HOME/.ssh/config" 2>/dev/null; then
	if [ -f "$HOME/.ssh/config" ]; then
		cp "$HOME/.ssh/config" "$HOME/.ssh/config.old"
		{ printf 'Include ~/.ssh/config.d/*\\n'; cat "$HOME/.ssh/config.old"; } > "$HOME/.ssh/config"
		rm -f "$HOME/.ssh/config.old"
	else
		printf 'Include ~/.ssh/config.d/*\\n' > "$HOME/.ssh/config"
	fi
	chmod 600 "$HOME/.ssh/config"
fi

cat > "$HOME/.ssh/config.d/pi-dictation" <<'CONFIG_EOF'
Host ${host}
  RemoteForward 127.0.0.1:47777 127.0.0.1:17777
  PermitLocalCommand yes
  LocalCommand sh -c 'nohup "$HOME/.local/bin/pi-mic-stream" >/dev/null 2>&1 &'
  # Successful connections need no forwarding log; every later one would warn.
  LogLevel ERROR
CONFIG_EOF

echo "Done. Reconnect to ${host}, then hold Space to dictate."
`;
}

/** The single line to run on the machine with the microphone. */
export function copyCommand(host: string): string {
	return `scp ${host}:${SETUP_SCRIPT} /tmp/ && sh ${SETUP_SCRIPT}`;
}

export async function writeSetup(host: string): Promise<string> {
	await writeFile(SETUP_SCRIPT, setupScript(host, await readHelper()), { mode: 0o644 });
	return copyCommand(host);
}
